package com.competra.domain.orienteering

/**
 * Режим проведённой жеребьёвки стартового протокола.
 *
 * Хранится в [com.competra.data.database.entity.OrienteeringCompetitions.drawMode] (null — жеребьёвка
 * не проводилась или проведена старым клиентом). Клиенты по нему подбирают свободную стартовую
 * минуту для опоздавшего участника (дозаявка) по тем же правилам, что и при жеребьёвке.
 */
enum class DrawMode {
    /** Общая: в одну минуту стартует один участник, группы чередуются. */
    GENERAL,

    /** По группам: в одну минуту стартует не больше одного участника группы. */
    GROUP,

    /**
     * По дистанциям: в одну минуту не больше `draw_corridors` участников и не больше одного
     * с каждой дистанции, старты одной дистанции разнесены минимум на `draw_gap` интервалов.
     */
    DISTANCE;

    companion object {
        /** Неизвестное значение (клиент новее сервера) — null: режим не меняем. */
        fun fromStringOrNull(raw: String?): DrawMode? = entries.firstOrNull { it.name == raw }
    }
}
